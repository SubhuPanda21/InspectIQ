import PDFDocument from 'pdfkit';
import { TYPE_LABEL, followUp } from './detect.js';

const clean = (s) => String(s ?? '').replace(/[\u2013\u2014]/g, '-').replace(/[^\x20-\x7E -ÿ‘’“”…]/g, '?');
const SEV = { critical: '#d6402b', high: '#eb8c1e', medium: '#c9a008', low: '#2d5bd1' };
const STATUS = { fail: 'Action needed', review: 'Review', none: 'Nothing detected' };

export function reportPdf(rec, annotatedPng, stream) {
  const doc = new PDFDocument({ size: 'A4', margin: 50, info: { Title: 'Inspection report ' + clean(rec.asset), Producer: 'InspectIQ' } });
  doc.pipe(stream);
  const W = doc.page.width - 100;
  const text = (t, o = {}) => doc.font(o.bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(o.size || 10.5).fillColor(o.color || '#222').text(clean(t), { width: W, lineGap: 2, ...(o.opts || {}) });
  const H = (t) => { doc.moveDown(0.8); text(t, { bold: true, size: 13, color: '#111' }); doc.moveDown(0.25); };

  text('Inspection report', { bold: true, size: 22, color: '#111' });
  doc.moveDown(0.3);
  text('Asset: ' + (rec.asset || 'not specified'));
  text('Inspector: ' + (rec.inspector || 'not specified'));
  text('Date: ' + new Date(rec.createdAt).toISOString().slice(0, 10) + '    Sensitivity: ' + Math.round(rec.sensitivity * 100) + '%    Source: ' + (rec.source === 'sample' ? 'synthetic test panel' : 'uploaded photo'));
  if (rec.source === 'sample') text('This image was generated by the app for demonstration. It does not show a real asset.', { color: '#8a3b12', size: 9.5 });

  doc.moveDown(0.6);
  const ar = rec.height / rec.width;
  const iw = Math.min(W, 420), ih = iw * ar;
  const y0 = doc.y;
  doc.image(annotatedPng, doc.x, y0, { width: iw });
  doc.y = y0 + ih + 8;

  H('Summary');
  text(rec.narrative);

  H('Findings');
  if (!rec.defects.length) text('No findings at this sensitivity.');
  rec.defects.forEach((d) => {
    if (doc.y > doc.page.height - 120) doc.addPage();
    doc.font('Helvetica-Bold').fontSize(10.5).fillColor(SEV[d.severity]).text(clean('#' + d.id + '  ' + (TYPE_LABEL[d.type] || d.type) + '  (' + d.severity + ')'), { width: W, continued: false });
    text('Position x ' + d.cx + ', y ' + d.cy + ' px. Size ' + d.bbox.w + ' by ' + d.bbox.h + ' px' + (d.type === 'crack' || d.type === 'scratch' ? ', length about ' + d.length + ' px' : ', area ' + d.area + ' px') + '. Confidence ' + Math.round(d.confidence * 100) + '%.', { size: 9.5, color: '#444' });
    text('Suggested follow-up: ' + followUp(d), { size: 9.5, color: '#444' });
    doc.moveDown(0.4);
  });

  if (doc.y > doc.page.height - 180) doc.addPage();
  H('Checklist');
  rec.checklist.forEach((c) => text(c.item + ': ' + STATUS[c.status] + (c.count ? ' (' + c.count + ')' : '')));
  text('"Nothing detected" means the detector found nothing in the photo. It is not a pass.', { size: 9, color: '#777' });

  if (rec.notes) { H('Inspector notes'); text(rec.notes); }

  doc.moveDown(1);
  text('Method: classical image analysis (local contrast and colour anomaly detection, region labelling, rule-based classification). Pixel sizes are not converted to millimetres. Severity ratings use size and contrast in the photo only. Every finding must be confirmed by a qualified person on site.', { size: 8.5, color: '#777' });
  doc.end();
}
