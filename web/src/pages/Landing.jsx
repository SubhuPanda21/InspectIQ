import { useState } from 'react';
import { Link, useNavigate } from 'react-router-dom';
import { AnimatedGroup, InView, TextEffect } from '../motion';
import { Doodle, Sketch, SketchButton, Squiggle } from '../components/Sketch.jsx';
import { send } from '../api.js';

const STEPS = [
  ['upload', 'Upload a photo', 'A JPEG or PNG of a plate, weld, panel or pipe. It is resized to 800 pixels and the metadata is dropped.'],
  ['detect', 'It looks for trouble', 'Cracks, scratches, corrosion, pits and wear are found by comparing every pixel with its surroundings.'],
  ['review', 'You review the circles', 'Each finding is numbered, rated and explained. Move the sensitivity slider and the circles update.'],
  ['report', 'Get the report', 'A PDF with the marked-up photo, findings, a checklist and your notes.'],
];

export default function Landing() {
  const nav = useNavigate();
  const [busy, setBusy] = useState(false);
  const [err, setErr] = useState('');
  const sample = async () => { setBusy(true); setErr(''); try { const r = await send('POST', '/inspections/sample', {}); nav('/i/' + r.id); } catch (e) { setErr(e.message); setBusy(false); } };

  return (
    <>
      <section className="hero">
        <div className="hero-text">
          <p className="eyebrow">For maintenance and quality teams</p>
          <TextEffect as="h1" per="word" preset="fade-in-blur" className="display">Photograph a surface. Get a numbered list of defects and a finished report.</TextEffect>
          <Squiggle />
          <InView delay={0.3}>
            <p className="lead">Upload a photo of a plate, weld, panel or pipe. InspectIQ finds cracks, scratches, corrosion and pits, circles each one, rates how serious it looks, fills in a checklist and writes the PDF.</p>
          </InView>
          <InView delay={0.45} className="cta-row">
            <Link to="/inspect" className="nolink"><SketchButton tone="yellow" tabIndex={-1}>Inspect a photo</SketchButton></Link>
            <SketchButton tone="white" onClick={sample} disabled={busy}>{busy ? 'Making a panel' : 'Try a test panel'}</SketchButton>
          </InView>
          {err ? <p className="alert" role="alert">{err}</p> : null}
        </div>
        <InView className="hero-art" delay={0.3} variants={{ hidden: { opacity: 0, rotate: 2, y: 30 }, visible: { opacity: 1, rotate: -1.2, y: 0 } }} duration={0.9}>
          <Sketch className="frame" fill="#fffdf6" seed={5}>
            <img src="/api/preview.png?seed=3" alt="A synthetic test panel with three defects circled and numbered by the detector" width="320" height="240" />
          </Sketch>
          <p className="caption">A synthetic test panel, analysed live by the detector. It is generated by the app, not a real asset.</p>
        </InView>
      </section>

      <section className="sec">
        <InView><h2>How it works</h2></InView>
        <AnimatedGroup className="steps" itemClassName="step-item" stagger={0.1}>
          {STEPS.map(([icon, title, text], i) => (
            <Sketch className="step" key={title} fill={i % 2 ? '#fff8e1' : '#fffdf6'} seed={i + 2}>
              <Doodle name={icon} size={54} delay={0.2} />
              <h3>{i + 1}. {title}</h3>
              <p>{text}</p>
            </Sketch>
          ))}
        </AnimatedGroup>
      </section>

      <section className="sec two">
        <InView>
          <h2>What it will not do</h2>
          <Squiggle color="#2d5bd1" />
        </InView>
        <InView delay={0.1}>
          <ul className="notes">
            <li>It does not measure depth or convert pixels to millimetres. Severity comes from size and contrast in the photo.</li>
            <li>It uses image analysis rules, not a trained model. Dirt, shadows and glare can look like defects, and faint damage can be missed.</li>
            <li>"Nothing detected" is not a pass. It means the detector saw nothing in that photo.</li>
            <li>A qualified person must confirm every finding on site.</li>
          </ul>
        </InView>
      </section>

      <section className="sec two">
        <InView>
          <h2>Measured, not promised</h2>
          <Squiggle color="#2f8a46" />
        </InView>
        <InView delay={0.1}>
          <p className="lead">The accuracy page runs the detector on generated panels where the true defect positions are known, and shows precision and recall at every sensitivity setting. The panels are synthetic, so treat the numbers as a way to compare settings, not as a field guarantee.</p>
          <Link to="/accuracy" className="nolink"><SketchButton tone="white" tabIndex={-1}>See the accuracy test</SketchButton></Link>
        </InView>
      </section>
    </>
  );
}
