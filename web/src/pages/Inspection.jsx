import { useCallback, useEffect, useRef, useState } from 'react';
import { Link, useNavigate, useParams } from 'react-router-dom';
import { api, fileUrl, imageUrl, send } from '../api.js';
import { AnimatedGroup, AnimatedNumber, InView, TextEffect } from '../motion';
import { Doodle, Sketch, SketchButton, Squiggle } from '../components/Sketch.jsx';
import Overlay, { SEV_COLOR } from '../components/Overlay.jsx';

const TYPE = { crack: 'Crack', scratch: 'Scratch', corrosion: 'Corrosion', pit: 'Pit', wear: 'Surface wear', glare: 'Bright spot, maybe glare' };
const FOLLOW = {
  crack: 'Treat cracks as structural until a qualified person says otherwise.',
  corrosion: 'Plan cleaning and protection. Check remaining thickness where it looks deepest.',
  scratch: 'Check whether the coating or base metal is breached.',
  pit: 'Measure depth. Pits can keep growing under coating.',
  wear: 'Compare with the previous inspection to estimate the rate.',
  glare: 'Likely lighting. Retake from another angle before acting.',
};
const STATUS = { fail: 'Action needed', review: 'Review', none: 'Nothing detected' };

export default function Inspection() {
  const { id } = useParams();
  const nav = useNavigate();
  const [rec, setRec] = useState(null);
  const [err, setErr] = useState('');
  const [active, setActive] = useState(null);
  const [view, setView] = useState('photo');
  const [truth, setTruth] = useState(false);
  const [busy, setBusy] = useState(false);
  const timers = useRef({});
  const [sens, setSens] = useState(0.7);
  const [notes, setNotes] = useState('');
  const [asset, setAsset] = useState('');
  const [inspector, setInspector] = useState('');

  useEffect(() => {
    api('/inspections/' + id).then((r) => { setRec(r); setSens(r.sensitivity); setNotes(r.notes); setAsset(r.asset); setInspector(r.inspector); }).catch((e) => setErr(e.message));
    return () => Object.values(timers.current).forEach(clearTimeout);
  }, [id]);

  const save = useCallback((key, patch, applyAll) => {
    clearTimeout(timers.current[key]);
    timers.current[key] = setTimeout(async () => {
      try { setBusy(true); const r = await send('PATCH', '/inspections/' + id, patch); setRec((old) => ({ ...r, ...(applyAll ? {} : { }) })); } catch (e) { setErr(e.message); } finally { setBusy(false); }
    }, key === 'sens' ? 350 : 700);
  }, [id]);
  const pick = useCallback((n) => { setActive(n); const el = document.getElementById('finding-' + n); if (el) el.scrollIntoView({ behavior: 'smooth', block: 'nearest' }); }, []);

  if (err && !rec) return <div className="page"><p className="alert" role="alert">{err}</p><Link to="/inspect">Start a new inspection</Link></div>;
  if (!rec) return <div className="page"><p className="muted">Loading</p></div>;

  const remove = async () => { if (!window.confirm('Delete this inspection and its photo?')) return; await send('DELETE', '/inspections/' + id); nav('/inspections'); };
  const src = view === 'heat' ? imageUrl(id, 'heatmap') : imageUrl(id, 'image', '&v=' + rec.createdAt);
  const real = rec.defects.filter((d) => d.type !== 'glare');

  return (
    <div className="page wide">
      <div className="insp-head">
        <div>
          <label htmlFor="asset" className="sr">Asset</label>
          <input id="asset" className="title-input" value={asset} onChange={(e) => { setAsset(e.target.value); save('asset', { asset: e.target.value }); }} placeholder="Name this asset" maxLength={100} />
          <p className="muted">{rec.source === 'sample' ? 'Synthetic test panel generated by the app. ' : ''}{new Date(rec.createdAt).toLocaleString()}</p>
        </div>
        <span className="status" aria-live="polite">{busy ? 'Updating' : ''}</span>
      </div>
      {err ? <p className="alert" role="alert">{err}</p> : null}

      <div className="insp-grid">
        <div>
          <Sketch className="viewer" fill="#fffdf6" seed={4}>
            <div className="stage" style={{ aspectRatio: rec.width + ' / ' + rec.height }}>
              <img src={src} alt={view === 'heat' ? 'Heat map of anomaly strength' : 'Inspected surface'} width={rec.width} height={rec.height} />
              {view === 'photo' ? <Overlay width={rec.width} height={rec.height} defects={rec.defects} activeId={active} truth={rec.truth} showTruth={truth} onPick={pick} /> : null}
            </div>
          </Sketch>
          <div className="toggles" role="group" aria-label="View options">
            <button className={'tog' + (view === 'photo' ? ' on' : '')} onClick={() => setView('photo')}>Photo with circles</button>
            <button className={'tog' + (view === 'heat' ? ' on' : '')} onClick={() => setView('heat')}>Anomaly heat map</button>
            {rec.truth ? <button className={'tog' + (truth ? ' on' : '')} onClick={() => setTruth(!truth)} disabled={view !== 'photo'}>Show true defect positions</button> : null}
          </div>
          {truth && rec.truth ? <p className="muted small">Dashed green boxes are where the generator actually drew defects. Compare them with the circles to judge the detector yourself.</p> : null}

          <label htmlFor="sens">Sensitivity: {Math.round(sens * 100)}%</label>
          <input id="sens" type="range" min="0" max="1" step="0.05" value={sens} onChange={(e) => { const v = Number(e.target.value); setSens(v); save('sens', { sensitivity: v }); }} />
          <p className="muted small">Higher finds fainter marks and more false alarms. The detector re-runs on the server each time you stop moving the slider.</p>

          <h2>Notes</h2>
          <label htmlFor="who" className="sr">Inspector</label>
          <input id="who" value={inspector} onChange={(e) => { setInspector(e.target.value); save('inspector', { inspector: e.target.value }); }} placeholder="Inspector name" maxLength={100} />
          <label htmlFor="notes" className="sr">Notes</label>
          <textarea id="notes" data-lenis-prevent rows={4} value={notes} onChange={(e) => { setNotes(e.target.value); save('notes', { notes: e.target.value }); }} placeholder="Lighting, access, what to check on site" maxLength={2000} />
        </div>

        <div>
          <h2>Findings <span className="count">{real.length}</span></h2>
          <Squiggle />
          <p className="summary">{rec.narrative}</p>
          {rec.defects.length === 0 ? <Sketch className="empty" fill="#f1f8ee" seed={12}><Doodle name="check" size={44} color="#2f8a46" /><p>No findings at this sensitivity. Try a higher setting, or retake the photo with better light.</p></Sketch> : null}
          <AnimatedGroup className="flist" itemClassName="fitem" stagger={0.07}>
            {rec.defects.map((d) => (
              <button id={'finding-' + d.id} key={d.id} className={'finding' + (active === d.id ? ' on' : '')} onClick={() => setActive(active === d.id ? null : d.id)} aria-pressed={active === d.id}>
                <span className="num" style={{ color: SEV_COLOR[d.severity], borderColor: SEV_COLOR[d.severity] }}>{d.id}</span>
                <span className="ftext">
                  <strong>{TYPE[d.type]}</strong>
                  <span className="sev" style={{ color: SEV_COLOR[d.severity] }}>{d.severity}</span>
                  <span className="muted small">{d.bbox.w} by {d.bbox.h} px{d.type === 'crack' || d.type === 'scratch' ? ', length about ' + d.length + ' px' : ', area ' + d.area + ' px'}. Confidence {Math.round(d.confidence * 100)}%.</span>
                  {active === d.id ? <span className="small">{FOLLOW[d.type]}</span> : null}
                </span>
              </button>
            ))}
          </AnimatedGroup>

          <h2>Checklist</h2>
          <ul className="check">
            {rec.checklist.map((c) => (
              <li key={c.item} className={c.status}><span className="box" aria-hidden="true">{c.status === 'fail' ? 'x' : c.status === 'review' ? '?' : ''}</span><span>{c.item}</span><em>{STATUS[c.status]}{c.count ? ' (' + c.count + ')' : ''}</em></li>
            ))}
          </ul>
          <p className="muted small">"Nothing detected" is not a pass. It only means the detector saw nothing in this photo.</p>

          <h2>Take it with you</h2>
          <div className="cta-row">
            <a href={fileUrl(id, 'report.pdf')} className="nolink" download><SketchButton tone="yellow" tabIndex={-1}>Download PDF report</SketchButton></a>
            <a href={imageUrl(id, 'annotated', '&download=1')} className="nolink" download><SketchButton tone="white" tabIndex={-1}>Marked-up image</SketchButton></a>
          </div>
          <p><button className="textlink danger" onClick={remove}>Delete this inspection</button></p>
        </div>
      </div>
    </div>
  );
}
